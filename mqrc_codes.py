"""IBM MQ constants: completion/reason codes, PCF selectors, protocol values.

Provenance
----------
Every constant in this module is documented in publicly available sources.
The values were cross-checked programmatically against two independent
open-source references, with zero value disagreements:

  * pymqi 1.12.13 (BSD licence, PyPI) -- CMQC.py, CMQCFC.py, CMQXC.py,
    CMQZC.py, 4858 named constants. Confirms the reason-code, completion-code
    and PCF selector tables, the MQI option flags (MQOO_/MQGMO_/MQPMO_/
    MQMO_/MQCO_/MQOT_), and the MQI structure lengths.
  * Wireshark (GPL-2.0) -- epan/dissectors/packet-mq.h and packet-mq.c.
    Confirms the RemoteFAP segment types (our RFP_TST_* == its MQ_TST_*, by
    value) and the MQMD/MQGMO/MQPMO/MQDLH field layouts from which the
    *_OFFSET values here are derived.

Naming differences from those references are cosmetic; the values match:

    ours                    published equivalent
    ------------------------------------------------------
    MQMD_V1_SIZE     324    MQMD_LENGTH_1            (pymqi)
    MQMD_V2_SIZE     364    MQMD_LENGTH_2            (pymqi)
    MQGMO_V1_SIZE     72    MQGMO_LENGTH_1           (pymqi)
    MQGMO_V2_SIZE     80    MQGMO_LENGTH_2           (pymqi)
    MQOD_V1_SIZE     168    MQOD_LENGTH_1            (pymqi)
    MQPMO_V1_SIZE    128    MQPMO_LENGTH_1           (pymqi)
    MQDLH_SIZE       172    MQDLH_LENGTH_1           (pymqi)
    MQPRI_AS_Q_DEF    -1    MQPRI_PRIORITY_AS_Q_DEF  (pymqi)
    RFP_TST_API_CALL 140    MQ_TST_SPI               (Wireshark)
    RFP_TST_API_REPLY 156   MQ_TST_SPI_REPLY         (Wireshark)

The *_OFFSET constants are not published as named constants by IBM; they are
plain arithmetic over the documented field order and field widths of the
corresponding structures.

CAUTION -- MQENC_NATIVE is platform-dependent. The value here (273 = 0x111)
is the big-endian/z-Series native encoding. On a little-endian host the
native value is 546 (0x222), which is what pymqi reports. Check this against
the byte order actually negotiated for the connection before relying on it.
"""

